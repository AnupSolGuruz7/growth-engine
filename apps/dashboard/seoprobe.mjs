import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1400, height: 1000 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
await p.goto('http://localhost:5180/seo', { waitUntil: 'networkidle' });
await p.getByTestId('run-audit').click();
await p.getByTestId('seo-score').waitFor({ timeout: 90_000 });
await p.waitForTimeout(800);
await p.screenshot({ path: `${process.env.TEMP}/seo-1.png`, fullPage: true });
await p.locator('.ant-table-row').first().click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${process.env.TEMP}/seo-2.png` });
await p.keyboard.press('Escape');
await p.waitForTimeout(400);
await p.getByRole('tab', { name: 'Pages' }).click();
await p.waitForTimeout(800);
await p.locator('.ant-tabs-tabpane-active .ant-table-row').first().click();
await p.waitForTimeout(1200);
await p.screenshot({ path: `${process.env.TEMP}/seo-3.png` });
console.log('score', await p.getByTestId('seo-score').innerText(), 'errors:', errs.length ? errs : 'none');
await b.close();
